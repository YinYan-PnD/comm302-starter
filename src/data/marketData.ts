// Helper to generate chart points
function generatePoints(
  basePrice: number,
  trend: 'up' | 'down' | 'volatile',
  count: number,
  labels: string[]
) {
  const points = [];
  let current = basePrice;
  const factor = trend === 'up' ? 0.003 : trend === 'down' ? -0.002 : 0.001;

  for (let i = 0; i < count; i++) {
    const noise = (Math.random() - 0.48) * (basePrice * 0.004);
    current = Math.max(current * 0.8, current + current * factor + noise);
    const open = current - (Math.random() - 0.5) * (basePrice * 0.002);
    const high = Math.max(open, current) + Math.random() * (basePrice * 0.002);
    const low = Math.min(open, current) - Math.random() * (basePrice * 0.002);
    points.push({
      time: labels[i] || `P${i}`,
      price: parseFloat(current.toFixed(2)),
      open: parseFloat(open.toFixed(2)),
      high: parseFloat(high.toFixed(2)),
      low: parseFloat(low.toFixed(2)),
      volume: Math.floor(Math.random() * 5000000 + 1000000),
    });
  }
  return points;
}

